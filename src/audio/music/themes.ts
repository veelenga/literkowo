export function arrangementFor(themeId: ThemeId, mood: MusicMood): Arrangement {
  const theme = THEMES[themeId];
  const isBoss = mood === 'boss';
  const themeSeed = hashSeed([themeId]);
  return {
    tempo: isBoss ? theme.tempo * BOSS_TEMPO_FACTOR : theme.tempo,
    swing: theme.swing,
    tonicMidi: theme.tonicMidi,
    mode: isBoss ? theme.bossMode : theme.calmMode,
    melodyDegrees: theme.melodyDegrees,
    progression: theme.progression,
    barsPerChord: theme.barsPerChord,
    space: theme.space,
    layers: [...BOSS_DRIVE, ...theme.layers, SPARKLE]
      .map((spec, index) => ({ spec, seed: themeSeed + index }))
      .filter(({ spec }) => (spec.mood ?? mood) === mood)
      .sort((first, second) => priorityOf(first.spec) - priorityOf(second.spec)),
  };
}

function priorityOf(spec: LayerSpec): number {
  const isIntensityLayer = spec.kind === 'motif' && spec.followsIntensity;
  return isIntensityLayer ? INTENSITY_LAYER_PRIORITY : KIND_PRIORITY[spec.kind];
}
